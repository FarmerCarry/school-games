  // gap = free height, top = ceiling row. extras = [[col, row, char], ...]
  function tunnel(w, pts, gap, top, extras) {
    var grid = [], r, c, los = [], his = [];
    for (r = 0; r <= top; r++) { grid.push([]); for (c = 0; c < w; c++) grid[r].push('.'); }
    for (c = 0; c < w; c++) {
      var k = 0;
      while (k < pts.length - 2 && pts[k + 1][0] <= c) k++;
      var a = pts[k], b = pts[k + 1], t = Math.max(0, Math.min(1, (c - a[0]) / (b[0] - a[0])));
      var y = a[1] + (b[1] - a[1]) * t, g = typeof gap === 'function' ? gap(c) : gap;
      var lo = Math.round(y - g / 2), hi = Math.round(y + g / 2);
      for (r = 0; r < lo; r++) grid[r][c] = '#';
      for (r = Math.max(hi, 0); r <= top; r++) grid[r][c] = '#';
      los[c] = lo; his[c] = hi;
    }
    // extras: row may be a number, 'f' (on the floor), 'c' (under the ceiling) or 'f+2' style offsets
    (extras || []).forEach(function (e) {
      var row = e[1];
      if (typeof row === 'string') {
        var base = row[0] === 'f' ? los[e[0]] : row[0] === 'm' ? Math.floor((los[e[0]] + his[e[0]]) / 2) : his[e[0]] - 1;
        row = base + (row.length > 1 ? +row.slice(1) : 0);
      }
      grid[row][e[0]] = e[2];
    });
    var rows = [];
    for (r = top; r >= 0; r--) rows.push(grid[r].join(''));
    return rows;
  }

