// The committed sw.js is the generated kill switch (tools/build.mjs --kill-sw),
// not a hand-written cache. OWN_FILES is the same path list the release worker
// precaches. test:offline.mjs byte-compares this file with a fresh generator run.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const catalogSource = fs.readFileSync(path.join(repo, 'js/catalog.js'), 'utf8');
const catalog = { window: {} };
vm.runInNewContext(catalogSource, catalog);
const games = catalog.window.GAMES;
const categories = new Set(catalog.window.CATEGORIES.map(category => category.id));
const INPUT = new Set(['one-button', 'pointer', 'keyboard', 'mixed']);
const ARABIC = /[\u0600-\u06FF]/;

function ownFiles() {
  const worker = fs.readFileSync(path.join(repo, 'sw.js'), 'utf8');
  assert.match(worker, /^\/\* Emergency switch generated by tools\/build\.mjs --kill-sw/);
  const match = worker.match(/^var OWN_FILES = (\[.*\]);$/m);
  assert.ok(match, 'kill switch lists OWN_FILES on one line');
  const files = JSON.parse(match[1]);
  assert.ok(Array.isArray(files) && files.length > 0);
  assert.deepEqual(files, [...files].sort(), 'OWN_FILES stays in the generator order');
  return new Set(files);
}

test('every catalog game is on the committed precache list', () => {
  const files = ownFiles();
  const missing = [];
  for (const game of games) {
    const rel = `games/${game.slug}/index.html`;
    if (!files.has(rel)) missing.push(rel);
    else assert.equal(fs.existsSync(path.join(repo, 'games', game.slug, 'index.html')), true, rel + ' exists');
  }
  assert.deepEqual(missing, []);
});

test('every catalog entry is well-formed, including Lucky Lake', () => {
  assert.equal(catalogSource.includes('<<<<<<<'), false, 'catalog.js has no merge conflict marker');
  assert.equal(catalogSource.includes('>>>>>>>'), false, 'catalog.js has no merge conflict marker');
  assert.ok(Array.isArray(games) && games.length > 0);
  const slugs = games.map(game => String(game.slug));
  assert.equal(new Set(slugs).size, slugs.length, 'duplicate slugs: ' + slugs.filter((slug, index) => slugs.indexOf(slug) !== index).join(', '));
  const problems = [];
  for (const game of games) {
    const where = game && game.slug ? game.slug : '(missing slug)';
    if (!game || typeof game !== 'object') { problems.push(where + ': not an object'); continue; }
    if (typeof game.slug !== 'string' || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(game.slug)) problems.push(where + ': slug');
    if (typeof game.title !== 'string' || !ARABIC.test(game.title)) problems.push(where + ': Arabic title');
    if (typeof game.blurb !== 'string' || !ARABIC.test(game.blurb)) problems.push(where + ': Arabic blurb');
    if (typeof game.en !== 'string' || !game.en.trim()) problems.push(where + ': English name');
    if (game.tags != null && typeof game.tags !== 'string') problems.push(where + ': tags');
    if (game.tip != null && typeof game.tip !== 'string') problems.push(where + ': tip');
    if (!Array.isArray(game.cats) || game.cats.length === 0 || game.cats.some(id => !categories.has(id))) problems.push(where + ': cats');
    if (typeof game.players !== 'string' || !/^\d+(?:-\d+)?$/.test(game.players)) problems.push(where + ': players');
    if (typeof game.color !== 'string' || !/^#[0-9a-f]{6}$/i.test(game.color)) problems.push(where + ': color');
    if (!INPUT.has(game.inputStyle)) problems.push(where + ': inputStyle');
    const minutes = game.roundMinutes;
    if (!(minutes === null || (Array.isArray(minutes) && minutes.length === 2 && minutes.every(n => typeof n === 'number' && n >= 0) && minutes[0] <= minutes[1]))) {
      problems.push(where + ': roundMinutes');
    }
    if (!Array.isArray(game.controls) || game.controls.length === 0) problems.push(where + ': controls');
    else {
      game.controls.forEach((row, index) => {
        const keys = row && row.keys;
        const keysOk = Array.isArray(keys) && keys.length > 0 && keys.every(key => typeof key === 'string' && key.length > 0);
        if (!keysOk || typeof row.action !== 'string' || !row.action.trim()) problems.push(where + ': controls[' + index + ']');
      });
    }
  }
  assert.deepEqual(problems, []);

  const lake = games.find(game => game.slug === 'lucky-lake');
  assert.ok(lake, 'lucky-lake catalog entry');
  assert.equal(lake.title, 'بحيرة الحظ');
  assert.equal(lake.en.includes('Lucky Lake'), true);
  assert.equal(lake.players, '1-2');
  assert.equal(lake.inputStyle, 'mixed');
  assert.equal(lake.color, '#2ec4ff');
  assert.deepEqual([...lake.cats], ['two-player', 'idle']);
  assert.deepEqual([...lake.roundMinutes], [3, 15]);
  assert.equal(ARABIC.test(lake.blurb), true);
  assert.equal(lake.blurb.includes('\uFFFD'), false);
  assert.equal(lake.controls.length, 7);
  assert.deepEqual([...Object.keys(lake)].sort(), [
    'blurb', 'cats', 'color', 'controls', 'en', 'inputStyle', 'players', 'roundMinutes', 'slug', 'tags', 'tip', 'title'
  ]);
});
